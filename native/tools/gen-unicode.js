// Writes src/unicode_tables.h: the Unicode facts the text helpers need, taken from this Node's
// own tables so the C port classifies and re-cases characters exactly as the JavaScript does.
//   node native/tools/gen-unicode.js
const fs = require("node:fs");
const path = require("node:path");

function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    const hit = !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  if (start >= 0) out.push([start, 0x10ffff]);
  return out;
}

function table(name, rs) {
  return `static const unsigned ${name}[][2] = {\n${rs.map(([a, b]) => `{0x${a.toString(16)},0x${b.toString(16)}}`).join(",").replace(/((?:[^,]+,[^,]+,){6})/g, "$1\n")}\n};\n`;
}

// One code point to one code point, where the two differ. Strings that change length under
// upper-casing ("ß" to "SS") go in a list of their own.
const lower = [];
const upper = [];
const upperLong = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const s = String.fromCodePoint(cp);
  const lo = [...s.toLowerCase()];
  const up = [...s.toUpperCase()];
  if (lo.length === 1 && lo[0] !== s) lower.push([cp, lo[0].codePointAt(0)]);
  if (up.length === 1 && up[0] !== s) upper.push([cp, up[0].codePointAt(0)]);
  if (up.length > 1) upperLong.push([cp, up.join("")]);
}
const pairs = (name, list) =>
  `static const unsigned ${name}[][2] = {\n${list.map(([a, b]) => `{0x${a.toString(16)},0x${b.toString(16)}}`).join(",").replace(/((?:[^,]+,[^,]+,){6})/g, "$1\n")}\n};\n`;
const utf8 = (s) => [...Buffer.from(s, "utf8")].map((b) => `\\x${b.toString(16).padStart(2, "0")}`).join("");

const out =
  `// Generated by tools/gen-unicode.js from Node ${process.version} (Unicode ${process.versions.unicode}). Do not edit.\n` +
  table("unicode_letter", ranges(/\p{L}/u)) +
  table("unicode_number", ranges(/\p{N}/u)) +
  table("unicode_lowercase_letter", ranges(/\p{Ll}/u)) +
  table("unicode_space", ranges(/\s/u)) +
  pairs("unicode_to_lower", lower) +
  pairs("unicode_to_upper", upper) +
  `static const struct { unsigned cp; const char *upper; } unicode_upper_long[] = {\n${upperLong.map(([cp, s]) => `{0x${cp.toString(16)},"${utf8(s)}"}`).join(",\n")}\n};\n`;
fs.writeFileSync(path.join(__dirname, "../src/unicode_tables.h"), out);
console.log(`unicode_tables.h: ${out.length} bytes, ${lower.length} lower, ${upper.length} upper, ${upperLong.length} long`);
