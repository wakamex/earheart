// Writes src/defaults.h from the Electron build's settings defaults (main/settings.js) and cleanup
// styles (main/cleanup-styles.js), so both builds start from the same settings and prompts.
//   node native/tools/gen-defaults.js
const fs = require("node:fs");
const path = require("node:path");
const { DEFAULTS } = require("../../main/settings");
const { STYLES, DEFAULT_STYLE, NEUTRAL_SAMPLING } = require("../../main/cleanup-styles");

// A C string literal, split so no line runs long.
const lit = (s) =>
  JSON.stringify(s)
    .slice(1, -1)
    .replace(/\?/g, "\\?")
    .match(/(?:\\.|[^\\]){1,100}/g)
    .map((part) => `    "${part}"`)
    .join("\n");

const out =
  `// Generated by tools/gen-defaults.js from main/settings.js and main/cleanup-styles.js. Do not edit.\n` +
  `static const char eh_defaults_json[] =\n${lit(JSON.stringify(DEFAULTS))};\n\n` +
  `static const struct { const char *id, *label, *hint, *directive; double temperature, top_p; int top_k; double min_p; } eh_styles[] = {\n` +
  STYLES.map((s) => `    { ${JSON.stringify(s.id)}, ${JSON.stringify(s.label)}, ${JSON.stringify(s.hint)},\n  ${lit(s.directive).trim()},\n      ${s.sampling.temperature}, ${s.sampling.topP}, ${s.sampling.topK}, ${s.sampling.minP} },`).join("\n") +
  `\n};\n#define EH_DEFAULT_STYLE ${JSON.stringify(DEFAULT_STYLE)}\n` +
  `#define EH_NEUTRAL_TOP_P ${NEUTRAL_SAMPLING.topP}\n#define EH_NEUTRAL_TOP_K ${NEUTRAL_SAMPLING.topK}\n#define EH_NEUTRAL_MIN_P ${NEUTRAL_SAMPLING.minP}\n`;
fs.writeFileSync(path.join(__dirname, "../src/defaults.h"), out);
console.log(`defaults.h: ${out.length} bytes`);
