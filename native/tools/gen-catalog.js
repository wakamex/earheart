// Writes src/catalog.c from the Electron build's model catalogue (main/engines/registry.js), so
// both builds download the same files at the same pinned commits while they exist side by side.
//   node native/tools/gen-catalog.js
const fs = require("node:fs");
const path = require("node:path");
const { MODELS } = require("../../main/engines/registry");

const q = (s) => (s == null ? "NULL" : JSON.stringify(String(s)));
let out = `// Generated by tools/gen-catalog.js from main/engines/registry.js. Do not edit.
#include "catalog.h"
#include <stddef.h>

`;
const rows = [];
for (const kind of ["stt", "cleanup"]) {
  for (const m of Object.values(MODELS[kind])) {
    const sym = `files_${m.id.replace(/[^a-z0-9]/gi, "_")}`;
    out += `static const eh_model_file ${sym}[] = {\n`;
    for (const f of m.files) out += `    { ${q(f.name)}, ${f.bytes}LL, ${q(f.sha256)}, ${q(f.url)} },\n`;
    out += `};\n`;
    const s = m.sherpa || {};
    rows.push(
      `    { ${q(m.id)}, ${q(m.label)}, ${q(m.note)}, ${kind === "stt" ? "EH_MODEL_STT" : "EH_MODEL_CLEANUP"}, ${!!m.default}, ${sym}, ${m.files.length},\n` +
        `      { ${q(s.encoder)}, ${q(s.decoder)}, ${q(s.joiner)}, ${q(s.tokens)}, ${q(s.modelType)} }, ${q(m.gguf && m.gguf.file)} },\n`
    );
  }
}
out += `\nconst eh_model eh_catalog[] = {\n${rows.join("")}};\nconst int eh_catalog_count = ${rows.length};\n`;
fs.writeFileSync(path.join(__dirname, "../src/catalog.c"), out);
