// Writes src/icons.h: the tray icons of assets/ as byte arrays, so the app is one file.
//   node native/tools/gen-icons.js
const fs = require("node:fs");
const path = require("node:path");
const names = { tray: "tray@2x.png", tray_recording: "tray-recording@2x.png" };
let out = "// Generated by tools/gen-icons.js from assets/. Do not edit.\n";
for (const [name, file] of Object.entries(names)) {
  const bytes = fs.readFileSync(path.join(__dirname, "../../assets", file));
  out += `static const unsigned char icon_${name}[] = {\n${bytes.toString("hex").match(/.{1,32}/g).map((row) => "    " + row.match(/../g).map((b) => `0x${b}`).join(",")).join(",\n")}\n};\n`;
}
fs.writeFileSync(path.join(__dirname, "../src/icons.h"), out);
// The app's own icon, for the windows: a file of its own, since only they use it.
const app = fs.readFileSync(path.join(__dirname, "../../assets/icon.png"));
fs.writeFileSync(
  path.join(__dirname, "../src/icon_app.h"),
  "// Generated by tools/gen-icons.js from assets/icon.png. Do not edit.\nstatic const unsigned char icon_app[] = {\n" +
    app.toString("hex").match(/.{1,32}/g).map((row) => "    " + row.match(/../g).map((b) => `0x${b}`).join(",") + ",").join("\n") +
    "\n};\n"
);
